export const DEFAULT_UNIVERSITY = ALL_BRAZILIAN_UNIVERSITIES.find(u => u.id === 'poli-usp') || ALL_BRAZILIAN_UNIVERSITIES[0];

/**
 * Intelligent detector for user-typed custom colleges
 * E.g., if user types "Faculdade de Engenharia de Taubaté" or "Universidade Estadual do Ceará" or "MIT"
 */
export function detectUniversityProfile(query: string): UniversityProfile {
  const q = query.trim().toLowerCase();

  // 1. Direct match with preset
  const directMatch = ALL_BRAZILIAN_UNIVERSITIES.find(
    u => u.name.toLowerCase().includes(q) || u.shortName.toLowerCase() === q
  );
  if (directMatch) return directMatch;

  // 2. Keyword heuristic detection
  let rigorScore = 80;
  let rigorCategory: RigorCategory = 'Alto (Padrão Federal)';
  let type: UniversityProfile['type'] = 'Federal';

  if (q.includes('ita') || q.includes('aeronautica') || q.includes('ime') || q.includes('militar')) {
    rigorScore = 98;
    rigorCategory = 'Extremo / Nível Olímpico';
    type = 'Militar';
  } else if (q.includes('usp') || q.includes('unicamp') || q.includes('ufrj') || q.includes('politecnica') || q.includes('poli')) {
    rigorScore = 95;
    rigorCategory = 'Muito Alto (Padrão USP/Unicamp/UFRJ)';
    type = 'Estadual';
  } else if (q.includes('uf') || q.includes('federal') || q.includes('unb') || q.includes('unesp') || q.includes('cefet') || q.includes('if')) {
    rigorScore = 90;
    rigorCategory = 'Alto (Padrão Federal)';
    type = 'Federal';
  } else if (q.includes('puc') || q.includes('mackenzie') || q.includes('maua') || q.includes('fei') || q.includes('insper')) {
    rigorScore = 85;
    rigorCategory = 'Médio-Alto (Excelência Privada)';
    type = 'Privada';
  } else if (q.includes('unip') || q.includes('estacio') || q.includes('anhanguera') || q.includes('pitagoras') || q.includes('anhembi') || q.includes('kroton')) {
    rigorScore = 73;
    rigorCategory = 'Didático / Aplicado';
    type = 'Privada';
  } else if (q.includes('mit') || q.includes('stanford') || q.includes('caltech') || q.includes('cambridge') || q.includes('eth')) {
    rigorScore = 99;
    rigorCategory = 'Extremo / Nível Olímpico';
    type = 'Personalizada';
  } else {
    // Custom university defaults to balanced high rigor (standard engineering bachelor)
    rigorScore = 82;
    rigorCategory = 'Alto (Padrão Federal)';
    type = 'Personalizada';
  }

  return {
    id: `custom-${Date.now()}`,
    name: query.trim(),
    shortName: query.trim().length > 18 ? query.trim().substring(0, 18) : query.trim(),
    state: 'BR',
    type: type,
    rigorScore: rigorScore,
    rigorCategory: rigorCategory,
    examStyle: `Perfil calibrado automaticamente pela IA para a instituição "${query.trim()}". Nível de rigor acadêmico ${rigorScore}/100 com resolução estruturada para engenharia.`,
    examDurationMinutes: 100,
    allowFormulaSheet: rigorScore < 85,
    typicalTopicsWeight: {
      'Cálculo e Teoremas Centrais': 35,
      'Física Teórica e Leis de Conservação': 30,
      'Álgebra e Equações Estruturais': 20,
      'Aplicações de Engenharia': 15,
    },
    strategicAdvice: `Para garantir nota máxima na ${query.trim()}, certifique-se de explicitar todas as hipóteses teóricas e unidades físicas.`,
    aiPromptDirective: `Adapte a resolução ao nível de rigor acadêmico ${rigorScore}/100 da instituição ${query.trim()}, mantendo demonstrações bem encadeadas.`
  };
}
